"""
Calculator module (imports lesson)

Simple arithmetic helpers: add, subtract, multiply, divide.
Imported by `01_imports.py` in the same directory.

The `if __name__ == "__main__"` block runs only when this file is executed
directly, not when imported.
"""

def add(a, b):
    return a + b


def subtract(a, b):
    return a - b


def multiply(a, b):
    return a * b


def divide(a, b):
    return a / b


if __name__ == "__main__":
    print("Calculator Started")
